    private void btnCalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalculateActionPerformed
String appointmentNo = txtAppointmentNo.getText().trim();

if (appointmentNo.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter appointment number."
    );
    txtAppointmentNo.requestFocus();
    return;
}

try {

    String encodedNo = java.net.URLEncoder.encode(
            appointmentNo,
            java.nio.charset.StandardCharsets.UTF_8
    );

    java.net.URL url = new java.net.URL(
            "http://localhost:8080/api/billing/calculate"
            + "?appointmentNo="
            + encodedNo
    );

    java.net.HttpURLConnection connection =
            (java.net.HttpURLConnection) url.openConnection();

    connection.setRequestMethod("GET");

    int responseCode = connection.getResponseCode();

    java.io.InputStream stream;

    if (responseCode >= 200 && responseCode < 300) {
        stream = connection.getInputStream();
    } else {
        stream = connection.getErrorStream();
    }

    java.util.Scanner scanner =
            new java.util.Scanner(stream);

    StringBuilder response =
            new StringBuilder();

    while (scanner.hasNextLine()) {
        response.append(scanner.nextLine());
    }

    scanner.close();

    String responseText = response.toString();

    if (responseCode == 200) {

        txtPatientName.setText(
                getJsonValue(responseText, "patientName")
        );

        txtTreatmentType.setText(
                getJsonValue(responseText, "treatmentType")
        );

        txtTreatmentCost.setText(
                getJsonValue(responseText, "treatmentCost")
        );

        txtConsultationFee.setText(
                getJsonValue(responseText, "consultationFee")
        );

        txtTotalAmount.setText(
                getJsonValue(responseText, "totalAmount")
        );

        txtBillDate.setText(
                getJsonValue(responseText, "billDate")
        );

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Appointment not found."
        );

        clearBillDetails();
    }

    connection.disconnect();

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Unable to connect to the server."
    );

    e.printStackTrace();
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnCalculateActionPerformed

