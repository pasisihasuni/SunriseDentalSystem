    private String getJsonValue(String json, String key) {

    String pattern = "\"" + key + "\":\"";

    int start = json.indexOf(pattern);

    if (start == -1) {
        return "";
    }

    start += pattern.length();

    int end = json.indexOf("\"", start);

    if (end == -1) {
        return "";
    }

    return json.substring(start, end);
}

